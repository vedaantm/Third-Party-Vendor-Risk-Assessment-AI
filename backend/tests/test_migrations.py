"""
Alembic migrations: the baseline builds the models' schema, `alembic check`
catches drift between models and migrations, and databases created by the
old create_all startup step are refused (not half-migrated) until stamped.

Every test uses a throwaway SQLite file — never Supabase.
"""

import argparse
import asyncio
from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

import app.db.models  # noqa: F401 — register tables
from app.db.database import Base

BACKEND = Path(__file__).resolve().parents[1]
TABLES = {"cert_cache", "evaluations", "jobs"}


def alembic_config(db_path: Path) -> Config:
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.attributes["skip_logging"] = True
    cfg.cmd_opts = argparse.Namespace(x=[f"url=sqlite+aiosqlite:///{db_path.as_posix()}"])
    return cfg


def schema(db_path: Path) -> dict:
    """Tables → columns (type, nullable), primary key, uniques, indexes."""
    engine = sa.create_engine(f"sqlite:///{db_path.as_posix()}")
    try:
        insp = sa.inspect(engine)
        out = {}
        for table in sorted(set(insp.get_table_names()) - {"alembic_version"}):
            out[table] = {
                "columns": {c["name"]: (str(c["type"]), c["nullable"]) for c in insp.get_columns(table)},
                "pk": insp.get_pk_constraint(table)["constrained_columns"],
                "unique": sorted(tuple(u["column_names"]) for u in insp.get_unique_constraints(table)),
                "indexes": sorted((i["name"], tuple(i["column_names"]), bool(i["unique"]))
                                  for i in insp.get_indexes(table)),
            }
        return out
    finally:
        engine.dispose()


def create_all(db_path: Path) -> None:
    """What main_api's lifespan did before migrations."""
    engine = sa.create_engine(f"sqlite:///{db_path.as_posix()}")
    Base.metadata.create_all(engine)
    engine.dispose()


def current_revision(db_path: Path) -> str | None:
    engine = sa.create_engine(f"sqlite:///{db_path.as_posix()}")
    try:
        with engine.connect() as conn:
            if "alembic_version" not in sa.inspect(conn).get_table_names():
                return None
            return conn.execute(sa.text("SELECT version_num FROM alembic_version")).scalar()
    finally:
        engine.dispose()


@pytest.fixture
def db(tmp_path):
    return tmp_path / "migrations.db"


# ── Baseline ──────────────────────────────────────────────

def test_upgrade_creates_every_table_at_the_baseline_revision(db):
    command.upgrade(alembic_config(db), "head")
    assert set(schema(db)) == TABLES
    assert current_revision(db) == "0001"


def test_migrated_schema_is_identical_to_create_all(db, tmp_path):
    # Proves an existing create_all database can safely be stamped at 0001
    command.upgrade(alembic_config(db), "head")
    legacy = tmp_path / "legacy.db"
    create_all(legacy)
    assert schema(db) == schema(legacy)


def test_downgrade_to_base_removes_every_table(db):
    cfg = alembic_config(db)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    assert schema(db) == {}
    assert current_revision(db) is None


def test_postgres_sql_renders_offline_without_a_database():
    # `alembic upgrade head --sql` must work with no connection (the guard
    # can't inspect tables offline); this is how the Postgres DDL is reviewed
    import io
    buffer = io.StringIO()
    cfg = Config(str(BACKEND / "alembic.ini"), output_buffer=buffer)
    cfg.attributes["skip_logging"] = True
    cfg.cmd_opts = argparse.Namespace(x=["url=postgresql+asyncpg://nobody:x@127.0.0.1:1/none"])
    command.upgrade(cfg, "head", sql=True)
    sql = buffer.getvalue()
    for table in TABLES:
        assert f"CREATE TABLE {table} (" in sql
    assert "TIMESTAMP WITH TIME ZONE" in sql and "UNIQUE (evaluation_id)" in sql
    assert "agent_outputs JSONB" in sql   # matches the production Supabase column
    assert "INSERT INTO alembic_version (version_num) VALUES ('0001')" in sql


def test_exactly_one_head():
    from alembic.script import ScriptDirectory
    heads = ScriptDirectory.from_config(alembic_config(Path("unused.db"))).get_heads()
    assert heads == ["0001"]


# ── Drift check (what CI runs as `alembic check`) ─────────

def test_models_and_migrations_agree(db):
    cfg = alembic_config(db)
    command.upgrade(cfg, "head")
    command.check(cfg)   # raises AutogenerateDiffsDetected on any difference


def test_check_fails_when_a_model_changes_without_a_migration(db):
    cfg = alembic_config(db)
    command.upgrade(cfg, "head")
    probe = sa.Column("added_without_migration", sa.String(10), nullable=True)
    Base.metadata.tables["jobs"].append_column(probe)
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="added_without_migration"):
            command.check(cfg)
    finally:
        table = Base.metadata.tables["jobs"]
        table._columns.remove(probe)
        assert "added_without_migration" not in table.c


# ── Databases created by the old create_all step ──────────

def test_upgrade_refuses_a_create_all_database_without_changing_it(db):
    create_all(db)
    before = schema(db)
    with pytest.raises(Exception, match="alembic stamp 0001"):
        command.upgrade(alembic_config(db), "head")
    assert schema(db) == before
    assert current_revision(db) is None


def test_stamped_create_all_database_checks_clean(db):
    create_all(db)
    cfg = alembic_config(db)
    command.stamp(cfg, "0001")
    assert current_revision(db) == "0001"
    command.check(cfg)
    command.upgrade(cfg, "head")   # already at head: a no-op, not an error


# ── Startup no longer creates tables ──────────────────────

def test_app_startup_does_not_create_tables(db, monkeypatch):
    import main_api
    from app.db.database import build_engine

    engine = build_engine(f"sqlite+aiosqlite:///{db.as_posix()}")
    monkeypatch.setattr(main_api, "engine", engine)

    async def start_and_stop():
        async with main_api.lifespan(main_api.app):
            pass
    asyncio.run(start_and_stop())
    assert schema(db) == {}


def test_agent_outputs_is_jsonb_on_postgres_and_json_elsewhere():
    from sqlalchemy.dialects import postgresql, sqlite
    column_type = Base.metadata.tables["evaluations"].c.agent_outputs.type
    assert column_type.compile(dialect=postgresql.dialect()) == "JSONB"
    assert column_type.compile(dialect=sqlite.dialect()) == "JSON"


# ── Real PostgreSQL (opt-in: `make test-postgres`) ────────
# Each test gets its own throwaway database on the server TEST_POSTGRES_URL
# points at (the local docker-compose Postgres), dropped afterwards.

import os
import uuid

from sqlalchemy.engine import make_url

TEST_POSTGRES_URL = os.environ.get("TEST_POSTGRES_URL")
requires_postgres = pytest.mark.skipif(
    not TEST_POSTGRES_URL, reason="set TEST_POSTGRES_URL (make test-postgres) to run against Postgres"
)


async def _admin(sql: str) -> None:
    import asyncpg
    u = make_url(TEST_POSTGRES_URL)
    conn = await asyncpg.connect(user=u.username, password=u.password, host=u.host,
                                 port=u.port, database=u.database)
    try:
        await conn.execute(sql)
    finally:
        await conn.close()


@pytest.fixture
def pg_url():
    name = f"vendoriq_test_{uuid.uuid4().hex[:10]}"
    asyncio.run(_admin(f'CREATE DATABASE "{name}"'))
    try:
        yield make_url(TEST_POSTGRES_URL).set(database=name).render_as_string(hide_password=False)
    finally:
        asyncio.run(_admin(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))


def pg_config(url: str) -> Config:
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.attributes["skip_logging"] = True
    cfg.cmd_opts = argparse.Namespace(x=[f"url={url}", "ssl=disable"])
    return cfg


def pg_run(url: str, fn):
    """Run fn(sync_connection) on a fresh engine and return its result."""
    from app.db.database import build_engine

    async def go():
        engine = build_engine(url, pooled=False, ssl="disable")
        try:
            async with engine.begin() as conn:
                return await conn.run_sync(fn)
        finally:
            await engine.dispose()
    return asyncio.run(go())


def pg_schema(url: str) -> dict:
    def read(conn):
        insp = sa.inspect(conn)
        return {
            t: {c["name"]: (str(c["type"]), c["nullable"]) for c in insp.get_columns(t)}
            for t in sorted(set(insp.get_table_names()) - {"alembic_version"})
        }
    return pg_run(url, read)


@requires_postgres
def test_postgres_upgrade_check_and_downgrade(pg_url):
    cfg = pg_config(pg_url)
    command.upgrade(cfg, "head")
    assert set(pg_schema(pg_url)) == TABLES
    assert pg_schema(pg_url)["evaluations"]["agent_outputs"][0] == "JSONB"
    command.check(cfg)
    command.downgrade(cfg, "base")
    assert pg_schema(pg_url) == {}


@requires_postgres
def test_postgres_migrated_schema_matches_create_all(pg_url):
    command.upgrade(pg_config(pg_url), "head")
    migrated = pg_schema(pg_url)
    command.downgrade(pg_config(pg_url), "base")
    pg_run(pg_url, Base.metadata.create_all)
    assert pg_schema(pg_url) == migrated


@requires_postgres
def test_postgres_create_all_database_is_refused_then_stamped(pg_url):
    pg_run(pg_url, Base.metadata.create_all)       # what Supabase looked like
    cfg = pg_config(pg_url)
    with pytest.raises(Exception, match="alembic stamp 0001"):
        command.upgrade(cfg, "head")
    command.stamp(cfg, "0001")
    command.check(cfg)
